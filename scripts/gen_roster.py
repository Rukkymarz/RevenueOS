"""Generates config/agents.yaml and one Agency-format companion (agents/<id>.md) per agent from
config/components.yaml (spec Addendum A1/A2). Every `kind: agent` component is an agent. Run with
--check in CI: the committed files must equal the generated ones."""
import sys
from pathlib import Path

import yaml

ROOT = Path(__file__).resolve().parents[1]
DIVISIONS = {   # Addendum A2: Engineering -> orchestrator, Design -> web, Marketing -> marketing, Social -> social, Research -> research
    "C01": "engineering", "C02": "engineering", "C03": "engineering", "C04": "engineering", "C06": "engineering",
    "C11": "engineering", "C13": "engineering", "C05": "marketing", "C07": "research", "C08": "design",
    "C09": "social", "C10": "marketing", "C14": "design"}
SERVICE = {"engineering": "orchestrator", "design": "web", "marketing": "marketing", "social": "social", "research": "research"}
MISSION = {
    "omnipilot": "Operate the computer (files, shell, GUI, browser) on the agent's behalf through governed syscalls.",
    "browser-use": "Drive a web browser with the agent's own profile to complete multi-step tasks on live sites.",
    "magenticlite": "Co-plan and co-execute web tasks with a human in the loop.",
    "openclaw-heartbeat": "Wake on a schedule, check the task list and ambient signals, and pick up work.",
    "ambient-watchers": "Watch mail, calendars and the web for events worth a task and raise them.",
    "leads-agent": "Qualify and route leads through the lead pipeline.",
    "agentic-pm": "Decompose a project into Spec, Plan and Rules, then a task tree, and track it.",
    "gsd-pi": "Run a slice end to end: plan, execute, verify, advance, reassess.",
    "fist-mbt": "Drive tasks through publish, claim, plan, execute, submit, verify and archive with watchdogs.",
    "openbusiness": "Turn a researched opportunity into a business plan and first assets.",
    "deepagents-open-lovable": "Generate a website from a design direction and framework contract.",
    "open-pages": "Build and revise generated websites.", "nexity": "Build web components against the framework contract.",
    "syntheon": "Synthesize designs and copy into page structures.",
    "verifier-agent": "Verify another agent's evidence with deterministic oracles; never the executor.",
    "curio": "Mine run history for skills and propose canaries.",
    "video-use": "Edit and assemble video.", "moneyprinterturbo": "Produce short videos from a topic.",
    "scrapegraph-ai": "Extract structured data from pages with schema-guided scraping.",
    "livekit-agents": "Hold real-time voice conversations."}


def load():
    comps = yaml.safe_load((ROOT / "config/components.yaml").read_text())["components"]
    return [c for c in comps if c["kind"] == "agent"]


def build():
    agents, files = [], {}
    for c in load():
        div = DIVISIONS[c["component"]]
        mission = MISSION.get(c["id"], f"Perform the {c['id']} role of {c['component']}.")
        buses = c.get("buses", [])
        tools = ["forage", "mcp.call"] if "mcp-gateway" in buses else []
        agents.append({"id": c["id"], "division": div, "service": SERVICE[div], "component": c["component"], "role": c["role"],
                       "companion": f"agents/{c['id']}.md"})
        files[f"agents/{c['id']}.md"] = f"""# {c['id']}

- **Division:** {div.capitalize()} (service: `{SERVICE[div]}`)
- **Component:** {c['component']} ({c['role']})

## Core mission
{mission}

## Technical deliverables
- Every action goes through the NAVA gateway as this agent's own identity; each produces a receipt.
- Evidence for each task it executes: kind, uri, sha-256, oracle tier (INV-01, INV-02).
- State shared with other agents lives in the memory server, not in the orchestrator.

## Success metrics
- Tasks reach COMPLETED only through a deterministic PASS from a different agent (INV-01, INV-03).
- Spend stays inside the agent budget; a halt is reported, not worked around (INV-08).
- No call outside its allowed tools and approved servers (INV-10).

## Allowed MCP tools
{chr(10).join('- `' + t + '`' for t in tools) if tools else '- none beyond the NAVA gateway syscalls it is granted'}
"""
    cfg = "# Generated by scripts/gen_roster.py from config/components.yaml. Do not edit by hand.\nagents:\n" + "".join(
        f"  - {{id: {a['id']}, division: {a['division']}, service: {a['service']}, component: {a['component']}, role: {a['role']}, companion: {a['companion']}}}\n"
        for a in agents)
    files["config/agents.yaml"] = cfg
    return files


def main() -> int:
    files = build()
    if "--check" in sys.argv:
        bad = [p for p, t in files.items() if not (ROOT / p).exists() or (ROOT / p).read_text() != t]
        extra = [str(p.relative_to(ROOT)) for p in (ROOT / "agents").glob("*.md") if str(p.relative_to(ROOT)) not in files]
        if bad or extra:
            print("roster out of date:", bad + extra, file=sys.stderr)
            return 1
        return 0
    for p, t in files.items():
        (ROOT / p).parent.mkdir(parents=True, exist_ok=True)
        (ROOT / p).write_text(t)
    print(f"wrote {len(files)} files")
    return 0


if __name__ == "__main__":
    sys.exit(main())
